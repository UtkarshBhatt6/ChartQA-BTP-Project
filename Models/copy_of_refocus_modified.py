def phi3v(model, processor, image1: Image.Image, image2: Image.Image, question: str, device: str = "cuda:0", max_new_tokens: int = 500) -> str:
    """
    Run inference on two images and a question using Phi-3 Vision.

    Args:
        model: Phi-3 Vision model (already loaded).
        processor: Corresponding processor (already loaded).
        image1 (PIL.Image.Image): The first image (with bounding box).
        image2 (PIL.Image.Image): The second image (zoomed-in version).
        question (str): The question to ask about the images.
        device (str): Device to run the model on ("cuda:0", "cpu", etc.).
        max_new_tokens (int): Maximum number of new tokens to generate.

    Returns:
        str: Model's textual response.
    """
    # Format the message with two images
    messages = [
        {"role": "user", "content": f"<|image_1|> \n<|image_2|> \nimage_1 is the image with bounding box drawn for the most important region and image_2 is the zoomed-in version of image_1.\n{question}"}
    ]

    # Create prompt from messages
    prompt = processor.tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True
    )

    # Prepare model inputs for both images
    inputs = processor(prompt, [image1, image2], return_tensors="pt").to(device)

    # Generate response
    generate_ids = model.generate(
        **inputs,
        eos_token_id=processor.tokenizer.eos_token_id,
        max_new_tokens=max_new_tokens,
        temperature=0.0,
        do_sample=False
    )

    # Remove prompt from output
    generate_ids = generate_ids[:, inputs['input_ids'].shape[1]:]

    # Decode the generated response
    response = processor.batch_decode(
        generate_ids,
        skip_special_tokens=True,
        clean_up_tokenization_spaces=False
    )[0]

    return response

def get_largest_bbox(bboxes):
    return max(bboxes, key=lambda b: (b['x2'] - b['x1']) * (b['y2'] - b['y1']))

