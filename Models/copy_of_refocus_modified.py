def refocus(model, processor, image: Image.Image, question: str, max_new_tokens: int = 1000) -> str:
    """
    Asks a question about an image using the Phi-3 Vision model.

    Args:
        model: The Phi-3 Vision model (loaded with `AutoModelForCausalLM`).
        processor: The corresponding processor (loaded with `AutoProcessor`).
        image (PIL.Image.Image): Input image.
        question (str): The question to ask about the image.
        max_new_tokens (int): Max tokens to generate in response.

    Returns:
        str: The model's answer.
    """
    # Create message
    messages = [
        {"role": "user", "content": f"<|image_1|>\n{question}"}
    ]

    # Create prompt
    prompt = processor.tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True,
    )

    # Process input
    inputs = processor(prompt, images=image, return_tensors="pt").to(model.device)

    # Generate
    generate_ids = model.generate(
        **inputs,
        eos_token_id=processor.tokenizer.eos_token_id,
        max_new_tokens=max_new_tokens,
        temperature=0.0,
        do_sample=False
    )

    # Remove prompt tokens
    generate_ids = generate_ids[:, inputs['input_ids'].shape[1]:]

    # Decode
    response = processor.batch_decode(
        generate_ids,
        skip_special_tokens=True,
        clean_up_tokenization_spaces=False
    )[0]

    return response

def extract_bounding_boxes(model_output: str) -> List[Dict[str, int]]:
    """
    Extracts a list of bounding box dictionaries from model output text.

    Args:
        model_output (str): The output string from the model.

    Returns:
        List[Dict[str, int]]: A list of bounding box dictionaries with keys 'x1', 'y1', 'x2', 'y2'.
    """
    # Match the full list of bounding boxes
    match = re.search(r"\[\s*{[^]]+}\s*\]", model_output)
    if match:
        try:
            bboxes = ast.literal_eval(match.group(0))
            if isinstance(bboxes, list) and all(isinstance(b, dict) for b in bboxes):
                return bboxes
        except (SyntaxError, ValueError):
            pass
    return []

