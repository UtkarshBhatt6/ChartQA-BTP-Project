def crop_image(image: Image.Image, bbox: dict, zoom_factor: int = 5) -> Image.Image:
    """
    Crops a region from the image using bbox and zooms into it.

    Args:
        image (PIL.Image.Image): Input image.
        bbox (dict): A dictionary with keys 'x1', 'y1', 'x2', 'y2' for cropping.
        zoom_factor (int): Factor to zoom the cropped region.

    Returns:
        PIL.Image.Image: The zoomed-in cropped region.
    """
    # Crop the region
    cropped_region = image.crop((bbox['x1'], bbox['y1'], bbox['x2'], bbox['y2']))

    # Resize (zoom) the cropped region
    zoomed_image = cropped_region.resize(
        (cropped_region.width * zoom_factor, cropped_region.height * zoom_factor),
        Image.LANCZOS  # High-quality resampling
    )

    return zoomed_image

from PIL import Image, ImageDraw

def draw_bboxes_on_image(image: Image.Image, bboxes: list) -> Image.Image:
    """
    Draws all bounding boxes on the image.

    Args:
        image (PIL.Image.Image): The image on which to draw the bounding boxes.
        bboxes (list): A list of dictionaries, where each dictionary contains
                       the bounding box coordinates ('x1', 'y1', 'x2', 'y2').

    Returns:
        PIL.Image.Image: The image with bounding boxes drawn.
    """
    # Create a drawing context
    draw = ImageDraw.Draw(image)

    # Draw each bounding box
    for bbox in bboxes:
        draw.rectangle(
            [(bbox['x1'], bbox['y1']), (bbox['x2'], bbox['y2'])],
            outline="red", width=3
        )

    return image

